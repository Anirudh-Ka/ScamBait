// Pre-records the built-in phone calls with Kokoro, an open-source neural voice
// model, so offline play and ElevenLabs outages still sound human.
//
// Usage:
//   pip install kokoro-onnx soundfile      (and ffmpeg on your PATH)
//   download kokoro-v1.0.int8.onnx and voices-v1.0.bin from
//   https://github.com/thewh1teagle/kokoro-onnx/releases/tag/model-files-v1.0
//   node scripts/render-voices.mjs <folder with the two model files>
//
// Writes src/voices/*.mp3 and src/voices/index.js. Re-run after editing the
// built-in call scripts in shared/seed.js.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { PERSONAS } from '../shared/personas.js';
import { buildSeedScenario } from '../shared/seed.js';
import { DEFLECT, CALL_PUSH } from '../shared/offline.js';
import { voiceKey, stripTags } from '../shared/voicekey.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'src/voices');
const modelDir = process.argv[2];
if (!modelDir) {
  console.error('Usage: node scripts/render-voices.mjs <kokoro model folder>');
  process.exit(1);
}

// Kokoro voices by caller type (Kokoro's best-rated American voices).
const KOKORO = {
  young_male: 'am_puck',
  young_female: 'af_heart',
  adult_male: 'am_michael',
  adult_female: 'af_bella',
  older_male: 'am_fenrir',
  older_female: 'af_nicole',
};

// Spell out things the English model would mispronounce.
function forKokoro(text) {
  return stripTags(text)
    .replace(/Chị/g, 'Chee')
    .replace(/Mẹ/g, 'Meh')
    .replace(/\$2,500/g, 'twenty-five hundred dollars');
}

const jobs = new Map();
function add(text, voice, speed) {
  const key = voiceKey(text);
  if (!key || jobs.has(key)) return;
  jobs.set(key, { id: `clip-${String(jobs.size + 1).padStart(2, '0')}`, key, text: forKokoro(text), voice: KOKORO[voice] || KOKORO.adult_male, speed });
}

const players = [...PERSONAS, { id: 'me', name: 'Test User', balance: 3000 }];
for (const p of players) {
  for (const m of buildSeedScenario(p).messages) {
    if (m.channel !== 'call') continue;
    const panicked = m.scamType === 'voice_clone';
    add(m.spoken || m.body, m.voice || 'adult_male', panicked ? 1.1 : 1.0);
    for (const r of m.replies || []) add(r, m.replyVoice || m.voice || 'adult_male', 1.02);
  }
}
for (const line of [...DEFLECT, ...CALL_PUSH]) add(line, 'adult_male', 1.02);

const list = [...jobs.values()];
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'scambait-voices-'));
const jobFile = path.join(tmp, 'jobs.json');
fs.writeFileSync(jobFile, JSON.stringify(list, null, 2));
console.log(`Rendering ${list.length} clips...`);

const py = spawnSync('python3', ['-I', path.join(root, 'scripts/kokoro_render.py'), jobFile, modelDir, outDir], { stdio: 'inherit' });
if (py.status !== 0) process.exit(py.status || 1);

// Remove clips that are no longer used.
const keep = new Set(list.map((j) => `${j.id}.mp3`));
for (const f of fs.readdirSync(outDir)) if (f.endsWith('.mp3') && !keep.has(f)) fs.unlinkSync(path.join(outDir, f));

const lines = [
  '// Generated by scripts/render-voices.mjs. Do not edit by hand.',
  '// Pre-recorded Kokoro voices for the built-in phone calls, keyed by the spoken line.',
  "import { voiceKey } from '../../shared/voicekey.js';",
  '',
  ...list.map((j, i) => `import c${i} from './${j.id}.mp3';`),
  '',
  'const CLIPS = {',
  ...list.map((j, i) => `  ${JSON.stringify(j.key)}: c${i},`),
  '};',
  '',
  'export function recordedClip(text) {',
  '  return CLIPS[voiceKey(text)] || null;',
  '}',
  '',
];
fs.writeFileSync(path.join(outDir, 'index.js'), lines.join('\n'));
console.log(`Wrote ${list.length} clips and src/voices/index.js`);
